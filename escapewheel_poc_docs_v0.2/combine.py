"""Render the informational entry point and numbered parts as one file.

The single-file rendering is a convenience, not a second source: every byte of it comes from the
parts, delimited so a reader can see which part a clause came from and a tool can split it back.
Generated rather than maintained, because a hand-concatenated copy is a second document that
agrees with the first only until someone edits one of them.

Run `python combine.py` after editing any part; `--check` fails where the rendering is stale,
which is what a CI step wants.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

#: The order the parts are presented in. The informational `README` comes first for orientation;
#: Part 00 and the subject-owning numbered parts carry the framework and identifiers.
ORDER = ("README.md", *(sorted(p.name for p in HERE.glob("[0-9][0-9]_*.md"))))

OUT = HERE / "Escapewheel_POC_v0.2_Implementation_Spec.md"
HTML_ID = re.compile(r'<a\s+[^>]*\bid="([^"]+)"[^>]*>')

HEADER = """<!--
Generated by combine.py from the parts in this directory. Do not edit.
Each part is delimited by BEGIN/END markers naming its file, so a clause cites the same
part number here as it does there.
-->
"""


def render() -> str:
    """Return the whole specification as one document."""
    blocks = [HEADER]
    for name in ORDER:
        body = (HERE / name).read_text().rstrip("\n")
        blocks.append(f"<!-- BEGIN {name} -->\n\n{body}\n\n<!-- END {name} -->\n")
    return "\n".join(blocks)


def duplicate_ids(rendered: str) -> list[str]:
    """Return raw-HTML anchor identifiers occurring more than once."""
    outside_fences = []
    fenced = False
    for line in rendered.splitlines():
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced:
            outside_fences.append(line)
    identifiers = HTML_ID.findall("\n".join(outside_fences))
    return sorted({value for value in identifiers if identifiers.count(value) > 1})


def main() -> int:
    """Write the rendering, or check that it is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the rendering is stale"
    )
    args = parser.parse_args()

    rendered = render()
    if duplicates := duplicate_ids(rendered):
        print(
            "combined specification has duplicate HTML identifiers: "
            + ", ".join(f"#{value}" for value in duplicates),
            file=sys.stderr,
        )
        return 1
    if args.check:
        current = OUT.read_text() if OUT.is_file() else ""
        if current != rendered:
            print(
                f"{OUT.name} is stale; run `python {Path(__file__).name}`",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT.name} is current")
        return 0

    OUT.write_text(rendered)
    words = len(rendered.split())
    print(f"wrote {OUT.name}: {len(ORDER)} parts, {words:,} words")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
