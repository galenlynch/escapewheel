"""What each section of each part is about, so a rewritten one cannot pass unnoticed.

A citation names a part and a section number, and `revisions/check_citations.py` resolves it
against the headings that exist. That check is blind to the failure that costs most: a section
keeping its number while its subject changes, which every citation of it survives and none of them
still means. R110 rewrote Part 03 §5.5, which 19 files cite, and nothing asked whether any of them
still held.

`headings.toml` is what makes that visible. It records the heading each section number carries, so
a changed heading is a diff, and the report naming every file citing that section comes with it --
`revisions/impact.py` run for whoever made the change rather than remembered by them.

A section that no longer exists is `check_citations.py`'s business, since a citation of it stops
resolving. This answers the question that one cannot: whether §5.5 is still about what its citers
took it for.

    python headings.py            # rewrite the record, reporting what changed and who cites it
    python headings.py --check    # the same, failing instead of rewriting
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import tomllib

HERE = Path(__file__).resolve().parent
LOCK = HERE / "headings.toml"

#: `## 3. Concepts` and `### 3.1 Dataset` alike, capturing the number and the subject separately.
HEADING = re.compile(r"^#{1,4} (\d+(?:\.\d+)*)\.? +(.+)$", re.MULTILINE)

PREAMBLE = """\
# What each section of each part is about. Generated by `headings.py`; never edited by hand.
#
# A section number is what a citation resolves through and a heading is what a citer relied on.
# `check_citations.py` checks the first and nothing checked the second, so a section could keep its
# number, change its subject, and leave every citation of it resolving to prose that no longer says
# what it was cited for.
#
# Changing a heading therefore means reading what cites it. `python headings.py` prints those
# citations and rewrites this file; committing it is the record that they were read.
"""


def cited_by(part: str, section: str) -> list[str]:
    """Every file citing this section, as `path:line`."""
    sys.path.insert(0, str(HERE.parent / "revisions"))
    from impact import citers

    return citers(part, section)


def current() -> dict[str, dict[str, str]]:
    """Each part's section numbers, mapped to the heading each one carries."""
    return {
        path.name[:2]: {
            number: title.strip() for number, title in HEADING.findall(path.read_text())
        }
        for path in sorted(HERE.glob("[0-9][0-9]_*.md"))
    }


def recorded() -> dict[str, dict[str, str]]:
    """What the record holds, or nothing where it has never been written."""
    return tomllib.loads(LOCK.read_text()) if LOCK.exists() else {}


def render(parts: dict[str, dict[str, str]]) -> str:
    """The record, each part in order and each section in the order the part declares it.

    A section number is a quoted key, since `2.1` unquoted would nest under `2` and a part that
    declared both would lose one to the other.
    """
    out = [PREAMBLE]
    for part in sorted(parts):
        out.append(f'\n["{part}"]\n')
        out += [
            f'"{number}" = {json.dumps(title)}\n'
            for number, title in parts[part].items()
        ]
    return "".join(out)


def drift(
    was: dict[str, dict[str, str]], now: dict[str, dict[str, str]]
) -> tuple[list, list, list]:
    """Each section whose heading changed, each one added, and each one no longer declared."""
    changed, added, gone = [], [], []
    for part in sorted(set(was) | set(now)):
        before, after = was.get(part, {}), now.get(part, {})
        for number, title in after.items():
            if number not in before:
                added.append((part, number, title))
            elif before[number] != title:
                changed.append((part, number, before[number], title))
        gone += [
            (part, number, title)
            for number, title in before.items()
            if number not in after
        ]
    return changed, added, gone


def main() -> int:
    """Report what has changed since the record was written, and rewrite it unless checking."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail rather than rewrite")
    args = parser.parse_args()

    now, was = current(), recorded()
    changed, added, gone = drift(was, now)

    # A changed heading is the one class nothing else sees, so its citers are listed. A section
    # that is gone breaks its citations, which `check_citations.py` reports as unresolved, and one
    # that is new can have none.
    for part, number, before, after in changed:
        print(
            f"  CHANGED  `{part}` §{number}\n             was  {before}\n             now  {after}"
        )
        for site in cited_by(part, number):
            print(f"             {site}")
    for part, number, title in gone:
        print(f"  GONE     `{part}` §{number}  {title}")
        for site in cited_by(part, number):
            print(f"             {site}")
    for part, number, title in added:
        print(f"  added    `{part}` §{number}  {title}")

    total = sum(len(sections) for sections in now.values())
    if not (changed or added or gone):
        print(f"{total} sections across {len(now)} parts, every heading as recorded")
        return 0
    tail = f"{len(changed)} heading(s) changed, {len(gone)} gone, {len(added)} added"
    if args.check:
        print(f"\n{tail}; read the citations above, then run `python headings.py`")
        return 1
    LOCK.write_text(render(now))
    print(f"\n{total} sections recorded; {tail}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
