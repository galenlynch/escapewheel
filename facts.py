"""Fill the counts in the root documents from the things they count.

Every number in `CLAUDE.md`, `STATUS.md` and `TODO.md` was hand-maintained, and every one of them
went stale: 35 tables against 34, 292 columns against 315, 282 checks against 299, 24 corpus
packets against 26, "R43-R53 accepted" against R43-R70. They were corrected three times in one
day and drifted again within the same day, which is the signature of a number that should not be
typed.

Each document carries regions delimited by `<!-- BEGIN facts: NAME -->` and `<!-- END facts: NAME
-->`; this script fills them from the registry, the revisions and the corpus. `verify.py` runs it
and then demands a clean git tree, so a stale count fails the build.

Test counts are deliberately not here. They require running the suites, and a document that could
only be regenerated by a five-minute job is a document people regenerate less often than they
change it.
"""

from __future__ import annotations

import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REGISTRY = ROOT / "registry/logical_schemas.json"
DOCUMENTS = ("CLAUDE.md", "STATUS.md", "TODO.md", "DEVELOPING.md")

REGION = re.compile(r"(<!-- BEGIN facts: (\w+) -->\n).*?(<!-- END facts: \2 -->)", re.DOTALL)


def _check_counts() -> tuple[int, int]:
    """How many invariants `registry/check.py` holds, counted from the source that holds them.

    Split the way the file is: `structural` runs once per registry document, so each of its checks
    binds core and every extension, while the rest run once over the whole set. Counted by parsing
    rather than by running, since `check.py` needs DuckDB to finish and this must not.
    """
    tree = ast.parse((ROOT / "registry/check.py").read_text())
    structural = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "structural")
    nested = {id(n) for n in ast.walk(structural)}

    def calls(scope, name, exclude=frozenset()):
        return sum(1 for n in ast.walk(scope) if isinstance(n, ast.Call)
                   and getattr(n.func, "id", None) == name and id(n) not in exclude)

    return calls(structural, "c_"), calls(tree, "check", nested)


def _clause_count() -> int:
    """Decision clauses across the accepted revisions, from the ledger that disposes of them.

    Imported rather than recounted: what counts as a clause is `ledger.py`'s judgement, and a
    second implementation here would be a second answer.
    """
    sys.path.insert(0, str(ROOT / "escapewheel_poc_docs_v0.2"))
    import ledger

    return len(ledger.clauses())


def _revision_span(numbers: set[int]) -> str:
    """Render a set of revision numbers as contiguous ranges: {1..3,5} -> `R1-R3 and R5`."""
    runs, start = [], None
    for n in sorted(numbers) + [None]:
        if start is None:
            start, previous = n, n
        elif n == previous + 1:
            previous = n
        else:
            runs.append(f"R{start}" if start == previous else f"R{start}–R{previous}")
            start, previous = n, n
    return " and ".join([", ".join(runs[:-1]), runs[-1]] if len(runs) > 1 else runs)


def facts() -> dict[str, str]:
    """Every count the root documents state, computed from what states it."""
    registry = json.loads(REGISTRY.read_text())
    tables = registry["tables"]
    columns = [c for t in tables.values() for c in t["columns"]]
    rules = [r for t in tables.values() for r in t["rules"]]
    advisory = sum(1 for r in rules if r.get("advisory"))
    references = sum(len(t["references"]) for t in tables.values())

    # Tier 1 is derived from structure, so its shape is countable without the validator.
    not_null = sum(1 for c in columns if c["presence"] == "required")
    vocabulary = sum(1 for c in columns if c.get("enum"))
    discriminators = sum(1 for c in columns if c.get("role") == "discriminator")

    accepted, withdrawn, proposed = set(), set(), set()
    for path in (ROOT / "revisions").glob("R*.md"):
        number = int(re.match(r"R(\d+)", path.name).group(1))
        head = path.read_text()[:400]
        (accepted if "**Accepted**" in head else withdrawn if "withdrawn" in head.lower() else proposed).add(number)
    # A draft carries no number until it is accepted, so the numbered space reads in the order
    # revisions were applied rather than written. `revisions/drafts/README.md` holds the order.
    drafts = [p for p in (ROOT / "revisions/drafts").glob("*.md") if p.name != "README.md"]

    extensions = sorted(p.stem for p in (ROOT / "registry/extensions").glob("*.json"))
    per_document, whole = _check_counts()
    decision_clauses = _clause_count()
    corpus = len(re.findall(r'^\s+"', (ROOT / "fixtures/corpus.py").read_text().split("EXPECTED")[1].split("}")[0], re.MULTILINE))

    return {
        "registry": (f"{len(tables)} tables, {len(columns)} columns, {references} references, "
                     f"{len(rules)} Tier 2 rules ({advisory} advisory)"),
        "revisions": (f"{_revision_span(accepted)} accepted. "
                      + (f"{_revision_span(withdrawn)} withdrawn. " if withdrawn else "")
                      + (f"{_revision_span(proposed)} proposed and not binding. " if proposed else "")
                      + (f"{len(drafts)} drafts are open in revisions/drafts/, none of them binding "
                         "and none numbered until accepted." if drafts
                         else "No draft is open.")),
        "tier1": (f"{not_null} not-null, {references} foreign-key, {vocabulary} closed-vocabulary "
                  f"and {2 * discriminators} discriminator checks, plus one uniqueness check per "
                  f"table whose sort does not begin with its primary key"),
        "extensions": f"{len(extensions)} extension registries: {', '.join(extensions)}",
        "corpus": f"{corpus} conformance packets",
        "checks": (f"{per_document} structural invariants, each applied to core and to each of the "
                   f"{len(extensions)} extension registries, and {whole} further checks over the "
                   f"whole set"),
        "clauses": (f"`ledger.py` enumerates {decision_clauses} Decision clauses across the "
                    f"accepted revisions."),
    }


def main() -> int:
    """Fill every marked region, reporting which documents changed."""
    filled = facts()
    changed = []
    for name in DOCUMENTS:
        path = ROOT / name
        before = path.read_text()
        named = {n for _, n, _ in REGION.findall(before)}
        if unknown := named - set(filled):
            raise SystemExit(f"{name} declares facts {sorted(unknown)} that facts.py does not compute")
        after = REGION.sub(lambda m: f"{m.group(1)}{filled[m.group(2)]}\n{m.group(3)}", before)
        if after != before:
            path.write_text(after)
            changed.append(name)
    print(f"filled {len(DOCUMENTS)} document(s)" + (f"; changed {', '.join(changed)}" if changed else "; no change"))
    for key, value in sorted(filled.items()):
        print(f"  {key:<11} {value}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
